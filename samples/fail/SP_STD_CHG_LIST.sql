-- 학적 변동 이력 조회 (에이전트 생성 원본: 명세에 없는 컬럼 포함)
CREATE OR REPLACE PROCEDURE SP_STD_CHG_LIST (
    P_YEAR    IN  VARCHAR2,
    P_TERM    IN  VARCHAR2,
    O_CUR     OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN O_CUR FOR
    SELECT A.STD_NO, B.STD_NM, B.MOBILE_NO, B.EMAIL, A.CHG_DIV_CD, A.CHG_DT
      FROM TB_STD_CHG A
      JOIN TB_STD_MST B ON B.STD_NO = A.STD_NO
     WHERE A.YEAR = P_YEAR
       AND A.TERM = P_TERM;
END;
/
