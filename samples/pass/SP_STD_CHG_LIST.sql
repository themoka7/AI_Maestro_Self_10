-- 학적 변동 이력 조회
CREATE OR REPLACE PROCEDURE SP_STD_CHG_LIST (
    P_YEAR    IN  VARCHAR2,
    P_TERM    IN  VARCHAR2,
    P_DEPT_CD IN  VARCHAR2,
    P_USER_ID IN  VARCHAR2,
    O_CUR     OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN O_CUR FOR
    SELECT A.STD_NO, B.STD_NM, B.DEPT_CD, A.CHG_DIV_CD, A.CHG_DT, A.CHG_RSN
      FROM TB_STD_CHG A
      JOIN TB_STD_MST B ON B.STD_NO = A.STD_NO
     WHERE A.YEAR = P_YEAR
       AND A.TERM = P_TERM
       AND B.DEPT_CD IN (SELECT DEPT_CD FROM TB_USER_DEPT_AUTH WHERE USER_ID = P_USER_ID);
END;
/
